const DICTS = { uz, en, ru };

/** Noma'lum yoki bo'sh til -> "uz". "en-US" kabi qiymatlardan faqat asosiy qism olinadi. */
function normLang(lang) {
  const base = String(lang || "").toLowerCase().split(/[-_]/)[0];
  return base in DICTS ? base : "uz";
}

/** Tarjima: {nom} o'rniga qiymat qo'yiladi. */
function tr(lang, key, vars) {
  let s = DICTS[normLang(lang)][key] ?? uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

module.exports = { tr, normLang, DICTS };
